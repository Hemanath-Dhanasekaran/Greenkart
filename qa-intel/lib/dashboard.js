'use strict';

/**
 * Builds the dashboard as ONE self-contained HTML file (styles, scripts and
 * data inlined), so it opens by double-click from a downloaded artifact or the
 * data branch without a web server, and needs no CDN or network access.
 */

const fs = require('fs');
const path = require('path');

const DASH = path.join(__dirname, '..', 'dashboard');
const read = (p) => fs.readFileSync(p, 'utf8');

/** JSON safe to embed inside <script>: no "</script>" or HTML comment openers. */
function embedJson(value) {
  // Escape <, U+2028 and U+2029 as JSON unicode escapes so the data cannot end the <script> element.
  const unsafe = new RegExp('[<' + String.fromCharCode(0x2028, 0x2029) + ']', 'g');
  return JSON.stringify(value).replace(unsafe, (ch) => `${'\\'}u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`);
}
const embedScript = (src) => src.replace(/<\/script/gi, '<\\/script');

function buildDashboardHtml(index) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>QA Intelligence</title>
<meta name="description" content="Test, framework and CI/CD history for ${String(index.repo || '').replace(/[<>"&]/g, '')}">
<style>
${read(path.join(DASH, 'styles.css'))}
</style>
</head>
<body>
<header class="top"><div class="top-inner">
  <div class="title-row"><h1>QA Intelligence</h1><span class="sub" id="repo-name"></span><span class="spacer"></span><button class="theme-btn" id="theme" type="button">Toggle theme</button></div>
  <div class="sub small muted" id="as-of"></div>
  <nav class="tabs" id="tabs" role="tablist"></nav>
</div></header>
<main id="main"></main>
<footer>Generated by qa-intel from recorded git history and GitHub Actions runs. Facts link to their source commit, run or report; inferred links are labelled.</footer>
<script>window.QA_INDEX = ${embedJson(index)};</script>
<script>${embedScript(read(path.join(__dirname, 'time.js')))}</script>
<script>${embedScript(read(path.join(__dirname, 'query.js')))}</script>
<script>${embedScript(read(path.join(DASH, 'app.js')))}</script>
</body>
</html>
`;
}

module.exports = { buildDashboardHtml, embedJson };
